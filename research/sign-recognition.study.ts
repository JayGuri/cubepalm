import { writeFileSync } from 'node:fs'
import { it } from 'vitest'
import { makeModelHand, type HandPose } from '../src/core/gestures/handModel'
import type { Landmark } from '../src/core/gestures/landmarks'
import {
  angleReader,
  distanceReader,
  featureVector,
  fingerFeatures,
  flatten,
  learnedReader,
  marginReader,
  squarePixels,
  type AngleThresholds,
  type LearnedWeights,
  type MarginThresholds,
  type PoseReader,
} from '../src/core/gestures/poseReaders'
import { POSE_FOR } from '../src/core/gestures/signGestures'
import { gaussian, percent, round, seeded, table, writeReport } from './report'

// How well is a pose read, and what makes it go wrong?
//
// Hands are generated by the model in src/core/gestures/handModel.ts, where the
// true pose is known. Each reader is scored on the same hands. The two readers
// that have something to fit (the angle reader's two thresholds, the learned
// reader's weights) are fitted on one random draw and scored on another.

const TRAIN_SEED = 20261011
const TEST_SEED = 7919
const PER_POSE = 250
const ASPECT = 4 / 3

// All sixteen ways four fingers can be up or down. Nine are signs; the other
// seven must be read as "not a sign", or a relaxed hand would turn the cube.
const ALL_POSES = Array.from({ length: 16 }, (_, n) => n.toString(2).padStart(4, '0'))
const SIGN_POSES = new Set(Object.values(POSE_FOR))

interface Setting {
  roll: () => number
  pitch: () => number
  yaw: () => number
  noise: () => number
  fingerLength: () => number
  /** Curl of a finger that is meant to be raised (0 is perfectly straight). */
  raised: () => number
  /** Curl of a finger that is meant to be folded (1 is a tight fist). */
  folded: () => number
  size: () => number
}

interface Sources {
  uniform: () => number
  normal: () => number
}

const between = (s: Sources, lo: number, hi: number) => lo + s.uniform() * (hi - lo)

/** A hand held well: facing the camera, upright, fingers clearly up or down. */
const nominal = (s: Sources): Setting => ({
  roll: () => 0,
  pitch: () => 0,
  yaw: () => 0,
  noise: () => 0.01,
  fingerLength: () => 1,
  raised: () => between(s, 0, 0.1),
  folded: () => between(s, 0.85, 1),
  size: () => 0.22,
})

/** A hand held the way people hold them: a bit turned, a bit tilted, fingers not quite straight. */
const mixed = (s: Sources): Setting => ({
  roll: () => s.normal() * 20,
  pitch: () => s.normal() * 20,
  yaw: () => s.normal() * 15,
  noise: () => between(s, 0.005, 0.03),
  fingerLength: () => between(s, 0.88, 1.12),
  raised: () => between(s, 0, 0.25),
  folded: () => between(s, 0.7, 1),
  size: () => between(s, 0.12, 0.3),
})

interface Sample {
  pose: string
  landmarks: Landmark[]
}

function draw(setting: Setting, s: Sources, perPose = PER_POSE): Sample[] {
  const samples: Sample[] = []
  for (const pose of ALL_POSES) {
    for (let i = 0; i < perPose; i++) {
      const hand: HandPose = {
        curl: [...pose].map((d) => (d === '1' ? setting.raised() : setting.folded())) as HandPose['curl'],
        handedness: s.uniform() < 0.5 ? 'Left' : 'Right',
        roll: setting.roll(),
        pitch: setting.pitch(),
        yaw: setting.yaw(),
        noise: setting.noise(),
        fingerLength: setting.fingerLength(),
        size: setting.size(),
        aspect: ASPECT,
        gaussian: s.normal,
      }
      samples.push({ pose, landmarks: makeModelHand(hand).landmarks })
    }
  }
  return samples
}

const sources = (seed: number): Sources => {
  const uniform = seeded(seed)
  return { uniform, normal: gaussian(uniform) }
}

// ---- Fitting ---------------------------------------------------------------

/** Every finger of every sample: its features (on square pixels) and whether it is raised. */
function fingerExamples(samples: Sample[]) {
  return samples.flatMap((sample) => {
    const square = squarePixels(sample.landmarks, ASPECT)
    return [0, 1, 2, 3].map((finger) => ({ finger, raised: sample.pose[finger] === '1', features: fingerFeatures(square, finger) }))
  })
}

/** The pair of thresholds that reads the most training fingers correctly. */
function fitAngleThresholds(samples: Sample[]): AngleThresholds {
  const examples = fingerExamples(samples)
  let best: AngleThresholds = { reach: 0.8, align: 0.5 }
  let bestCorrect = -1
  for (let reach = 0.5; reach <= 0.951; reach += 0.025) {
    for (let align = 0; align <= 0.901; align += 0.1) {
      const correct = examples.filter((e) => (e.features.reach > reach && e.features.align > align) === e.raised).length
      if (correct > bestCorrect) [best, bestCorrect] = [{ reach: round(reach, 3), align: round(align, 1) }, correct]
    }
  }
  return best
}

/**
 * Thresholds with a gap between them: 99 in 100 fingers meant to be raised are
 * straighter than `raisedReach` and point more with the palm than `raisedAlign`,
 * and 99 in 100 meant to be folded are less straight than `foldedReach`. What
 * falls between is read as neither.
 */
function fitMarginThresholds(samples: Sample[]): MarginThresholds {
  const examples = fingerExamples(samples)
  const sorted = (values: number[]) => [...values].sort((a, b) => a - b)
  const raised = examples.filter((e) => e.raised)
  const folded = examples.filter((e) => !e.raised)
  const at = (values: number[], q: number) => sorted(values)[Math.floor(q * (values.length - 1))]
  return {
    raisedReach: round(at(raised.map((e) => e.features.reach), 0.01), 3),
    raisedAlign: round(at(raised.map((e) => e.features.align), 0.01), 3),
    foldedReach: round(at(folded.map((e) => e.features.reach), 0.99), 3),
  }
}

/** Logistic regression by gradient descent, with a light pull toward small weights. */
function fitLearnedWeights(samples: Sample[]): LearnedWeights {
  const examples = fingerExamples(samples).map((e) => ({ finger: e.finger, y: e.raised ? 1 : 0, x: featureVector(e.features) }))
  const w = [0, 0, 0, 0, 0]
  const b = [0, 0, 0, 0]
  const rate = 0.5
  const pull = 1e-4
  for (let epoch = 0; epoch < 600; epoch++) {
    const gw = [0, 0, 0, 0, 0]
    const gb = [0, 0, 0, 0]
    for (const e of examples) {
      const z = e.x.reduce((sum, v, i) => sum + v * w[i], b[e.finger])
      const error = 1 / (1 + Math.exp(-z)) - e.y
      e.x.forEach((v, i) => (gw[i] += error * v))
      gb[e.finger] += error
    }
    w.forEach((_, i) => (w[i] -= rate * (gw[i] / examples.length + pull * w[i])))
    b.forEach((_, i) => (b[i] -= (rate * gb[i]) / examples.length))
  }
  return { features: w.map((v) => round(v, 4)) as LearnedWeights['features'], bias: b.map((v) => round(v, 4)) as LearnedWeights['bias'] }
}

// ---- Scoring ---------------------------------------------------------------

interface Score {
  /** Of hands making a sign, how many were read as exactly that sign. */
  signs: number
  /** Of hands making no sign, how many were read as some sign (each would turn the cube). */
  falseSigns: number
  /** Of all fingers, how many were read correctly. */
  fingers: number
}

function score(read: PoseReader, samples: Sample[]): Score {
  let signs = 0
  let signTotal = 0
  let falseSigns = 0
  let otherTotal = 0
  let fingers = 0
  for (const sample of samples) {
    const got = read(sample.landmarks)
    for (let f = 0; f < 4; f++) if (got[f] === sample.pose[f]) fingers++
    if (SIGN_POSES.has(sample.pose)) {
      signTotal++
      if (got === sample.pose) signs++
    } else {
      otherTotal++
      if (SIGN_POSES.has(got)) falseSigns++
    }
  }
  return { signs: signs / signTotal, falseSigns: falseSigns / otherTotal, fingers: fingers / (samples.length * 4) }
}

it('sign recognition study', () => {
  const train = draw(mixed(sources(TRAIN_SEED)), sources(TRAIN_SEED + 1))
  const thresholds = fitAngleThresholds(train)
  const weights = fitLearnedWeights(train)
  const margins = fitMarginThresholds(train)

  // Each reader is a way of preparing the landmarks plus a rule.
  const onSquare = (read: PoseReader): PoseReader => (l) => read(squarePixels(l, ASPECT))
  const readers: Array<{ name: string; note: string; read: PoseReader }> = [
    { name: 'Distance (shipped)', note: 'tip-to-wrist distance in hand sizes, one threshold of 1.4, landmarks as MediaPipe gives them', read: distanceReader() },
    { name: 'Distance, square pixels', note: 'the same rule after undoing the 4:3 stretch', read: onSquare(distanceReader()) },
    { name: 'Angle', note: `straight and pointing with the palm (reach > ${thresholds.reach}, align > ${thresholds.align}), square pixels`, read: onSquare(angleReader(thresholds)) },
    { name: 'Angle, no depth', note: 'the same without the depth coordinate', read: (l) => angleReader(thresholds)(flatten(squarePixels(l, ASPECT))) },
    {
      name: 'Angle with a dead zone',
      note: `raised when reach > ${margins.raisedReach} and align > ${margins.raisedAlign}, folded when reach < ${margins.foldedReach}, otherwise neither; square pixels`,
      read: onSquare(marginReader(margins)),
    },
    { name: 'Learned', note: 'logistic regression over five finger features, square pixels', read: onSquare(learnedReader(weights)) },
  ]

  const scoreAll = (samples: Sample[]) => readers.map((r) => score(r.read, samples))

  // 1. The realistic setting, on hands the fitted readers have not seen.
  const test = draw(mixed(sources(TEST_SEED)), sources(TEST_SEED + 1), PER_POSE * 2)
  const mixedScores = scoreAll(test)
  const trainScores = scoreAll(train)

  // 2. One thing varied at a time, everything else held well.
  const sweep = (label: string, values: number[], apply: (setting: Setting, value: number) => Setting, unit = '') => {
    const rows = values.map((value, i) => {
      const s = sources(TEST_SEED + 100 * (i + 1) + label.length)
      const samples = draw(apply(nominal(s), value), s)
      return [`${value}${unit}`, ...scoreAll(samples).map((sc) => percent(sc.signs))]
    })
    return { heading: label, body: table([label, ...readers.map((r) => r.name)], rows) }
  }
  const sweeps = [
    sweep('Turn in the picture (roll)', [0, 15, 30, 45, 60, 90], (st, v) => ({ ...st, roll: () => v }), '°'),
    sweep('Fingertips tipped toward the camera (pitch)', [-40, -20, 0, 20, 40, 60], (st, v) => ({ ...st, pitch: () => v }), '°'),
    sweep('Hand turned edge-on (yaw)', [0, 15, 30, 45, 60], (st, v) => ({ ...st, yaw: () => v }), '°'),
    sweep('Landmark jitter, as a fraction of hand size', [0, 0.01, 0.02, 0.04, 0.06, 0.08], (st, v) => ({ ...st, noise: () => v })),
    sweep('Finger length, relative to the model hand', [0.8, 0.9, 1, 1.1, 1.2], (st, v) => ({ ...st, fingerLength: () => v })),
    sweep('Raised fingers not fully straight (curl)', [0, 0.1, 0.2, 0.3, 0.4], (st, v) => ({ ...st, raised: () => v })),
    sweep('Folded fingers not fully closed (curl)', [1, 0.9, 0.8, 0.7, 0.6], (st, v) => ({ ...st, folded: () => v })),
    sweep('Hand size, as a fraction of picture height', [0.08, 0.12, 0.22, 0.32], (st, v) => ({ ...st, size: () => v })),
  ]

  // A relaxed hand: every finger about half curled. There is no right pose to
  // read, only a wrong outcome: calling it a sign.
  const relaxedSource = sources(TEST_SEED + 9000)
  const relaxed = Array.from({ length: 4000 }, () => {
    const st = mixed(relaxedSource)
    return makeModelHand({
      curl: [0, 1, 2, 3].map(() => between(relaxedSource, 0.35, 0.65)) as HandPose['curl'],
      roll: st.roll(),
      pitch: st.pitch(),
      yaw: st.yaw(),
      noise: st.noise(),
      fingerLength: st.fingerLength(),
      size: st.size(),
      aspect: ASPECT,
      gaussian: relaxedSource.normal,
    }).landmarks
  })
  const relaxedAsSign = readers.map((r) => relaxed.filter((l) => SIGN_POSES.has(r.read(l))).length / relaxed.length)

  // 3. Where the shipped rule goes wrong: its commonest misreadings in the realistic setting.
  const mistakes = new Map<string, number>()
  for (const sample of test) {
    const got = readers[0].read(sample.landmarks)
    if (got !== sample.pose) mistakes.set(`${sample.pose} read as ${got}`, (mistakes.get(`${sample.pose} read as ${got}`) ?? 0) + 1)
  }
  const worst = [...mistakes.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8)
  const fingerErrors = [0, 1, 2, 3].map((f) => test.filter((s) => readers[0].read(s.landmarks)[f] !== s.pose[f]).length / test.length)

  // The decision rule was fixed before any of these numbers existed (see the
  // plan): the best reader in the realistic setting, if more than a point ahead
  // of the shipped one. The relaxed-hand column was added after the timing
  // study showed that reading signs well is only half of it, so the verdict
  // reports both and leaves the choice of default to recordings of real hands.
  const shipped = mixedScores[0].signs
  const best = mixedScores.reduce((b, sc, i) => (sc.signs > mixedScores[b].signs ? i : b), 0)
  const verdict = [
    mixedScores[best].signs - shipped > 0.01
      ? `By signs read correctly, **${readers[best].name}** leads with ${percent(mixedScores[best].signs)} against ${percent(shipped)} for the shipped rule, more than the one point the rule fixed in advance asks for.`
      : `No reader beats the shipped rule (${percent(shipped)}) by more than one point on signs read correctly.`,
    'That is not the whole decision. A reader also has to leave a relaxed hand alone, and the readers differ far more on that than on anything else (third column). The dead-zone reader is the one built to do both.',
    'Because these are model hands, no reader replaces the default on this evidence. The dead-zone reader is offered as an option in Settings, and becomes the default only if recordings of real hands confirm it.',
  ].join(' ')

  // The fitted numbers become constants in the app, so the app and this report cannot drift apart.
  writeFileSync(
    'src/core/gestures/trainedReaders.ts',
    [
      "import type { AngleThresholds, LearnedWeights, MarginThresholds } from './poseReaders'",
      '',
      '// Written by research/sign-recognition.study.ts (`npm run research`). Do not edit by hand:',
      '// change the study and run it again. See docs/research/sign-recognition.md.',
      '',
      `export const TRAINED_ANGLE_THRESHOLDS: AngleThresholds = ${JSON.stringify(thresholds)}`,
      '',
      `export const TRAINED_MARGINS: MarginThresholds = ${JSON.stringify(margins)}`,
      '',
      `export const TRAINED_WEIGHTS: LearnedWeights = ${JSON.stringify(weights)}`,
      '',
    ].join('\n'),
  )

  writeReport({
    name: 'sign-recognition',
    title: 'Reading a hand sign: how well, and what breaks it',
    summary:
      'A sign is four fingers, each up or down. This measures how often that is read correctly by the rule the app shipped with and by four alternatives, on generated hands whose true pose is known. One thing is varied at a time to see what each reader is sensitive to, and a realistic mixed setting gives one headline number per reader.',
    parameters: {
      'Hand model': 'src/core/gestures/handModel.ts',
      'Picture shape': '4:3',
      Poses: `all ${ALL_POSES.length} finger patterns: ${SIGN_POSES.size} signs and ${ALL_POSES.length - SIGN_POSES.size} that are not signs`,
      'Hands per pose': `${PER_POSE} per row of each table; ${PER_POSE * 2} in the realistic test set`,
      'Fitted on': `${train.length} hands, seed ${TRAIN_SEED}`,
      'Scored on': `${test.length} different hands, seed ${TEST_SEED}`,
    },
    sections: [
      {
        heading: 'The readers',
        body: table(
          ['Reader', 'How it decides a finger is raised'],
          readers.map((r) => [r.name, r.note]),
        ),
      },
      {
        heading: 'Realistic setting',
        body: [
          'Roll and pitch drawn from a normal distribution with a standard deviation of 20°, yaw 15°, jitter between 0.5% and 3% of hand size, fingers 12% shorter to 12% longer, raised fingers curled up to a quarter of the way, folded fingers closed at least 70% of the way, hand size from 12% to 30% of the picture height.',
          '',
          table(
            ['Reader', 'Signs read correctly', 'Non-signs read as a sign', 'Relaxed hand read as a sign', 'Fingers read correctly', 'Signs correct on the fitting set'],
            readers.map((r, i) => [r.name, percent(mixedScores[i].signs), percent(mixedScores[i].falseSigns), percent(relaxedAsSign[i]), percent(mixedScores[i].fingers, 2), percent(trainScores[i].signs)]),
          ),
          '',
          'A relaxed hand has every finger between 35% and 65% curled: it is making no sign, and a reader that calls it one would turn the cube when nobody asked. The last column is the same measurement on the hands the fitted readers were fitted on. Where it is close to the first column, the fit has not simply memorised its examples.',
          '',
          verdict,
        ].join('\n'),
      },
      ...sweeps.map((s) => ({ heading: `Signs read correctly as one thing varies: ${s.heading.toLowerCase()}`, body: s.body })),
      {
        heading: 'Where the shipped rule goes wrong',
        body: [
          'Its most common misreadings in the realistic setting (true pose, then what was read; index finger first, 1 is raised):',
          '',
          table(
            ['Misreading', 'Count', 'Share of all hands'],
            worst.map(([what, count]) => [what, count, percent(count / test.length, 2)]),
          ),
          '',
          'How often each finger is misread:',
          '',
          table(['Index', 'Middle', 'Ring', 'Little'], [fingerErrors.map((e) => percent(e, 2))]),
        ].join('\n'),
      },
      {
        heading: 'Fitted values',
        body: [
          `Angle reader thresholds: reach > ${thresholds.reach}, align > ${thresholds.align}.`,
          '',
          `Dead-zone thresholds: raised when reach > ${margins.raisedReach} and align > ${margins.raisedAlign}; folded when reach < ${margins.foldedReach}.`,
          '',
          `Learned reader weights (reach, align, middle-joint bend, end-joint bend, tip ratio): ${weights.features.join(', ')}; offsets per finger (index to little): ${weights.bias.join(', ')}.`,
          '',
          'Both are written to `src/core/gestures/trainedReaders.ts`, which the app imports.',
        ].join('\n'),
      },
      {
        heading: 'What this does and does not show',
        body: [
          '- It shows how sensitive each reader is to each thing that varies, because here the true pose is known and everything else can be held still. That cannot be done with a camera.',
          '- It does not show accuracy on people. The hands are a model: rigid bones, joints that bend in one plane, jitter that is independent from landmark to landmark. Real tracking errors are not like that (a hidden finger is guessed, not jittered), and the proportions of the model hand were chosen by eye.',
          '- The two fitted readers were fitted on hands from the same model they are scored on. Beating the shipped rule here is a reason to test them on recordings of real hands, not proof that they are better on real hands.',
          '- Recordings made with the recorder at `/record` can be scored by the same code. Until some exist, treat every number here as a property of the readers, not of the app in use.',
        ].join('\n'),
      },
    ],
  })
})
