import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

// Every experiment writes its results through here, so every report in
// docs/research/ has the same shape and says how to reproduce itself.

export type Cell = string | number

/** A Markdown table. Numbers are right-aligned so columns of figures line up. */
export function table(headers: string[], rows: Cell[][]): string {
  const numeric = headers.map((_, c) => rows.length > 0 && rows.every((r) => typeof r[c] === 'number'))
  const line = (cells: Cell[]) => `| ${cells.join(' | ')} |`
  return [line(headers), line(headers.map((_, c) => (numeric[c] ? '---:' : '---'))), ...rows.map(line)].join('\n')
}

/** 0.9731 -> "97.3%". */
export const percent = (fraction: number, digits = 1) => `${(fraction * 100).toFixed(digits)}%`

/** A number to a fixed number of decimals, as a number (so tables right-align it). */
export const round = (value: number, digits = 2) => Number(value.toFixed(digits))

export interface Report {
  /** File name under docs/research/, without the extension. */
  name: string
  title: string
  /** One paragraph: what was measured and why. */
  summary: string
  /** Anything that fixes the result: seed, sample sizes, time budgets. */
  parameters: Record<string, Cell>
  /** Sections in order: a heading and its Markdown body. */
  sections: Array<{ heading: string; body: string }>
}

/** Writes docs/research/<name>.md and returns its path. */
export function writeReport(report: Report): string {
  const path = resolve('docs/research', `${report.name}.md`)
  mkdirSync(dirname(path), { recursive: true })
  const parameters = Object.entries(report.parameters)
    .map(([key, value]) => `- ${key}: ${value}`)
    .join('\n')
  const body = [
    `# ${report.title}`,
    '',
    `> Generated by \`npm run research\` (\`research/${report.name}.study.ts\`). Do not edit by hand: change the experiment and run it again.`,
    '',
    report.summary,
    '',
    '## Parameters',
    '',
    parameters,
    '',
    ...report.sections.flatMap((s) => [`## ${s.heading}`, '', s.body, '']),
  ].join('\n')
  writeFileSync(path, body.trimEnd() + '\n')
  return path
}

/**
 * A small, fast, seedable random generator (mulberry32). Experiments must be
 * repeatable, so none of them uses Math.random.
 */
export function seeded(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Standard normal samples from a uniform source (Box-Muller). */
export function gaussian(random: () => number): () => number {
  return () => {
    const u = Math.max(random(), 1e-12)
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * random())
  }
}
